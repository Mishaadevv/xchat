def normalize(text: str) -> str:
    return str(text or "").strip().lower()


def is_synthetic(instruction: str) -> bool:
    s = normalize(instruction)
    return bool(re.match(r"^повседневный\s+диалог\s+\d+:", s))


def main():
    data = json.loads(DATASET_PATH.read_text(encoding="utf-8"))
    everyday_raw = [x for x in data if isinstance(x, dict) and x.get("category") == "everyday"]
    coding = [x for x in data if isinstance(x, dict) and x.get("category") == "coding"]

    seen = set()
    everyday = []
    for row in everyday_raw:
        ins = str(row.get("instruction", "")).strip()
        resp = str(row.get("response", "")).strip()
        if not ins or not resp:
            continue
        if is_synthetic(ins):
            continue
        key = normalize(ins)
        if key in seen:
            continue
        seen.add(key)
        if key in MANUAL_RESPONSE:
            resp = MANUAL_RESPONSE[key]
        everyday.append({"instruction": ins, "response": resp, "category": "everyday"})

    for ins, resp in ADDITIONAL_EVERYDAY:
        key = normalize(ins)
        if not key or key in seen:
            continue
        seen.add(key)
        everyday.append({"instruction": ins, "response": resp, "category": "everyday"})

    final_data = everyday + coding
    DATASET_PATH.write_text(json.dumps(final_data, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"everyday={len(everyday)} coding={len(coding)} total={len(final_data)}")
    print("synthetic_left=", sum(1 for x in everyday if is_synthetic(x.get("instruction", ""))))


if __name__ == "__main__":
    main()
